import SwiftUI
import AppKit
import Carbon.HIToolbox

// MARK: - Умный буфер обмена
//
// История последних копирований (текст, картинки, файлы) при включённой настройке «Запоминать» сохраняется на диск (~/Library/Application Support/StartMenu/Clipboard)
// и восстанавливается при запуске; по умолчанию — только в памяти. Выключение умного буфера стирает и сохранённую копию.
// Закреплённые записи не вытесняются новыми и не считаются в лимите. Пароли не сохраняются: пропускаются копии,
// помеченные менеджерами паролей как скрытые, и всё, что скопировано из самих менеджеров паролей.
// Вход: ⇧⌘V (панель у курсора, выбор стрелками / цифрами, Enter вставляет) и значок на верхней панели «Пуска»
// (клик по записи копирует её в буфер).

struct ClipItem: Identifiable {
    enum Kind { case text, image, files }
    var id = UUID()
    var kind: Kind
    var text = ""
    var data: Data?
    var thumb: NSImage?
    var label = ""
    var urls: [URL] = []
    var pinned = false
    let key: String

    var singleLine: String {
        text.replacingOccurrences(of: "\r\n", with: " ").replacingOccurrences(of: "\n", with: " ")
            .replacingOccurrences(of: "\t", with: " ")
    }
}

final class ClipboardHistory: ObservableObject {
    static let shared = ClipboardHistory()
    static let marker: Int64 = 0x53464D43
    static let combo = Combo(keyCode: UInt32(kVK_ANSI_V), mods: UInt32(cmdKey | shiftKey), keyTitle: "V")
    static let hotKeyID: UInt32 = 15

    static var enabled: Bool {
        get { UserDefaults.standard.object(forKey: "clip.enabled") as? Bool ?? false }
        set { UserDefaults.standard.set(newValue, forKey: "clip.enabled") }
    }
    /// Запоминать историю между запусками (по умолчанию выключено)
    static var remember: Bool {
        get { UserDefaults.standard.object(forKey: "clip.remember") as? Bool ?? false }
        set { UserDefaults.standard.set(newValue, forKey: "clip.remember") }
    }
    static var limit: Int {
        get {
            let v = UserDefaults.standard.integer(forKey: "clip.limit")
            return [3, 5, 10].contains(v) ? v : 5
        }
        set { UserDefaults.standard.set(newValue, forKey: "clip.limit") }
    }

    @Published private(set) var items: [ClipItem] = [] {
        didSet { scheduleSave() }
    }
    private var loaded = false
    private var saveWork: DispatchWorkItem?
    @Published var enabled = ClipboardHistory.enabled

    private var timer: Timer?
    private var lastCount = NSPasteboard.general.changeCount
    private var suppressUntil = Date.distantPast
    /// Ближайшие `seconds` секунд изменения буфера в историю не попадают
    func suppress(for seconds: TimeInterval) { suppressUntil = Date().addingTimeInterval(seconds) }

    /// Закреплённые сверху, затем свежие
    var ordered: [ClipItem] { items.filter { $0.pinned } + items.filter { !$0.pinned } }

    private static let secretTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping",
        "Pasteboard generator type", "net.antelle.keeweb", "com.1password.1password"
    ]
    private static let secretApps = ["com.1password", "com.agilebits", "com.bitwarden", "org.keepassxc", "com.apple.keychainaccess",
                                     "com.apple.Passwords", "com.lastpass", "com.dashlane", "org.keepassx", "com.enpass",
                                     "ru.local.Safe", "com.apple.Safari.passwords"]

    // MARK: включение

    func setEnabled(_ on: Bool) {
        ClipboardHistory.enabled = on
        enabled = on
        if on {
            start()
        } else {
            stop()
            items.removeAll()
            saveWork?.cancel()
            try? FileManager.default.removeItem(at: ClipboardHistory.storeDir)
            loaded = false
        }
    }

    func start() {
        guard ClipboardHistory.enabled, timer == nil else { return }
        enabled = true
        if !loaded {
            loaded = true
            if ClipboardHistory.remember {
                let old = items
                load()
                if !old.isEmpty { items = old + items; trim() }
            }
            NotificationCenter.default.addObserver(forName: NSApplication.willTerminateNotification, object: nil, queue: .main) { [weak self] _ in
                self?.saveNow()
            }
        }
        lastCount = NSPasteboard.general.changeCount
        let t = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in self?.poll() }
        RunLoop.main.add(t, forMode: .common)
        timer = t
        HotKeyCenter.shared.register(ClipboardHistory.combo, id: ClipboardHistory.hotKeyID) {
            ClipPanelController.shared.toggle()
        }
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        HotKeyCenter.shared.unregister(id: ClipboardHistory.hotKeyID)
        ClipPanelController.shared.close()
    }

    func setRemember(_ on: Bool) {
        ClipboardHistory.remember = on
        if on {
            saveNow()
        } else {
            saveWork?.cancel()
            try? FileManager.default.removeItem(at: ClipboardHistory.storeDir)
        }
    }

    func setLimit(_ n: Int) {
        ClipboardHistory.limit = n
        trim()
        objectWillChange.send()
    }

    // MARK: сохранение между запусками

    private struct Stored: Codable {
        var kind: String
        var text: String
        var label: String
        var paths: [String]
        var pinned: Bool
        var key: String
        var file: String?
    }

    private static var storeDir: URL {
        FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("StartMenu/Clipboard", isDirectory: true)
    }

    private func scheduleSave() {
        guard loaded, ClipboardHistory.enabled, ClipboardHistory.remember else { return }
        saveWork?.cancel()
        let w = DispatchWorkItem { [weak self] in self?.saveNow() }
        saveWork = w
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.6, execute: w)
    }

    private func saveNow() {
        guard loaded, ClipboardHistory.enabled, ClipboardHistory.remember else { return }
        let fm = FileManager.default
        let dir = ClipboardHistory.storeDir
        try? fm.createDirectory(at: dir, withIntermediateDirectories: true)
        var out: [Stored] = []
        var keep: Set<String> = ["index.json"]
        for it in items {
            var st = Stored(kind: "", text: it.text, label: it.label, paths: it.urls.map { $0.path }, pinned: it.pinned, key: it.key, file: nil)
            switch it.kind {
            case .text: st.kind = "t"
            case .files: st.kind = "f"
            case .image:
                st.kind = "i"
                let name = it.id.uuidString + ".img"
                st.file = name
                keep.insert(name)
                let u = dir.appendingPathComponent(name)
                if !fm.fileExists(atPath: u.path), let d = it.data { try? d.write(to: u, options: .atomic) }
            }
            out.append(st)
        }
        if let d = try? JSONEncoder().encode(out) {
            try? d.write(to: dir.appendingPathComponent("index.json"), options: .atomic)
        }
        for f in (try? fm.contentsOfDirectory(atPath: dir.path)) ?? [] where !keep.contains(f) {
            try? fm.removeItem(at: dir.appendingPathComponent(f))
        }
    }

    private func load() {
        let dir = ClipboardHistory.storeDir
        guard let d = try? Data(contentsOf: dir.appendingPathComponent("index.json")),
              let list = try? JSONDecoder().decode([Stored].self, from: d) else { return }
        var res: [ClipItem] = []
        for st in list {
            switch st.kind {
            case "t":
                var it = ClipItem(kind: .text, key: st.key); it.text = st.text; it.pinned = st.pinned
                res.append(it)
            case "f":
                let urls = st.paths.map { URL(fileURLWithPath: $0) }
                guard !urls.isEmpty else { continue }
                var it = ClipItem(kind: .files, key: st.key); it.urls = urls; it.pinned = st.pinned
                res.append(it)
            case "i":
                guard let name = st.file, let data = try? Data(contentsOf: dir.appendingPathComponent(name)),
                      let img = NSImage(data: data) else { continue }
                var it = ClipItem(kind: .image, key: st.key)
                if let base = UUID(uuidString: (name as NSString).deletingPathExtension) { it.id = base }
                it.data = data; it.label = st.label; it.pinned = st.pinned
                it.thumb = ClipboardHistory.thumbnail(img, height: 72)
                res.append(it)
            default: break
            }
        }
        items = res
    }

    // MARK: слежение за буфером

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastCount else { return }
        lastCount = pb.changeCount
        if Date() < suppressUntil { return }                // свои временные копирования (переключатель раскладки) в историю не идут
        let types = (pb.types ?? []).map { $0.rawValue }
        guard !types.isEmpty else { return }
        if types.contains(where: { ClipboardHistory.secretTypes.contains($0) }) { return }
        if let id = NSWorkspace.shared.frontmostApplication?.bundleIdentifier?.lowercased(),
           ClipboardHistory.secretApps.contains(where: { id.hasPrefix($0.lowercased()) }) { return }

        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            add(ClipItem(kind: .files, urls: urls, key: "f:" + urls.map { $0.path }.joined(separator: "|")))
        } else if let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let t = s.count > 100_000 ? String(s.prefix(100_000)) : s
            add(ClipItem(kind: .text, text: t, key: "t:" + t))
        } else if let d = pb.data(forType: .tiff) ?? pb.data(forType: .png), d.count < 30_000_000,
                  let img = NSImage(data: d) {
            let key = "i:\(d.count):\(d.prefix(256).hashValue):\(d.suffix(256).hashValue)"
            var it = ClipItem(kind: .image, key: key)
            it.data = d
            it.thumb = ClipboardHistory.thumbnail(img, height: 72)
            if let rep = img.representations.first, rep.pixelsWide > 0 {
                it.label = "\(rep.pixelsWide)×\(rep.pixelsHigh)"
            }
            add(it)
        }
    }

    private static func thumbnail(_ img: NSImage, height: CGFloat) -> NSImage {
        let s = img.size
        guard s.height > 0 else { return img }
        let k = min(1, height / s.height)
        let size = NSSize(width: max(1, s.width * k), height: max(1, s.height * k))
        let out = NSImage(size: size)
        out.lockFocus()
        img.draw(in: NSRect(origin: .zero, size: size), from: .zero, operation: .copy, fraction: 1)
        out.unlockFocus()
        return out
    }

    private func add(_ item: ClipItem) {
        if let i = items.firstIndex(where: { $0.key == item.key }) {
            if items[i].pinned { return }
            items.remove(at: i)
        }
        items.insert(item, at: 0)
        trim()
    }

    private func trim() {
        var kept = 0
        items = items.filter { it in
            if it.pinned { return true }
            kept += 1
            return kept <= ClipboardHistory.limit
        }
    }

    // MARK: действия

    func togglePin(_ id: UUID) {
        guard let i = items.firstIndex(where: { $0.id == id }) else { return }
        items[i].pinned.toggle()
        trim()
    }

    func remove(_ id: UUID) { items.removeAll { $0.id == id } }

    func clearUnpinned() { items.removeAll { !$0.pinned } }

    /// Кладёт запись в буфер обмена (без повторного добавления в историю)
    func copy(_ item: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch item.kind {
        case .text: pb.setString(item.text, forType: .string)
        case .image: if let d = item.data { pb.setData(d, forType: .tiff) }
        case .files: pb.writeObjects(item.urls.map { $0 as NSURL })
        }
        lastCount = pb.changeCount
        if let i = items.firstIndex(where: { $0.id == item.id }), !items[i].pinned {
            let it = items.remove(at: i)
            items.insert(it, at: 0)
        }
    }

    /// Копирует запись и нажимает ⌘V в активном приложении (если выдан «Управление устройством и доступ к данным» (в ранних версиях macOS: «Универсальный доступ»))
    func paste(_ item: ClipItem) {
        copy(item)
        guard AXIsProcessTrusted() else { return }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.12) {
            let src = CGEventSource(stateID: .combinedSessionState)
            for down in [true, false] {
                guard let e = CGEvent(keyboardEventSource: src, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: down) else { continue }
                e.flags = .maskCommand
                e.setIntegerValueField(.eventSourceUserData, value: ClipboardHistory.marker)
                e.post(tap: .cgAnnotatedSessionEventTap)
            }
        }
    }
}

// MARK: Интерфейс списка

final class ClipUI: ObservableObject {
    @Published var selected = 0
}

struct ClipListView: View {
    @ObservedObject var history: ClipboardHistory
    @ObservedObject var ui: ClipUI
    let pasteMode: Bool
    let onPick: (ClipItem) -> Void

    private let digits = ["1", "2", "3", "4", "5", "6", "7", "8", "9", "0"]

    var body: some View {
        let list = history.ordered
        VStack(spacing: 0) {
            HStack {
                Text(T("Буфер обмена")).font(.system(size: 13, weight: .semibold))
                Spacer()
                Button(T("Очистить")) { history.clearUnpinned() }
                    .buttonStyle(.plain).font(.caption).foregroundColor(.secondary)
                    .disabled(!list.contains { !$0.pinned })
            }
            .padding(.horizontal, 12).padding(.vertical, 8)
            Divider()
            if list.isEmpty {
                Text(T("Пока пусто — скопируйте что-нибудь"))
                    .font(.callout).foregroundColor(.secondary)
                    .frame(maxWidth: .infinity).padding(.vertical, 22)
            } else {
                VStack(spacing: 2) {
                    ForEach(Array(list.enumerated()), id: \.element.id) { i, item in
                        row(i, item)
                    }
                }
                .padding(6)
            }
            Divider()
            Text(pasteMode ? T("↑↓ Enter — вставить · P — закрепить · ⌫ — убрать · Esc — закрыть")
                           : T("Клик — скопировать в буфер обмена"))
                .font(.caption2).foregroundColor(.secondary)
                .padding(.horizontal, 12).padding(.vertical, 6)
        }
        .frame(width: 340)
    }

    private func row(_ i: Int, _ item: ClipItem) -> some View {
        let selected = pasteMode && ui.selected == i
        return HStack(spacing: 8) {
            Text(i < 10 ? digits[i] : "")
                .font(.system(size: 11, design: .monospaced)).foregroundColor(.secondary).frame(width: 12)
            content(item)
            Spacer(minLength: 4)
            Button { history.togglePin(item.id) } label: {
                Image(systemName: item.pinned ? "pin.fill" : "pin")
                    .foregroundColor(item.pinned ? .accentColor : .secondary)
            }
            .buttonStyle(.plain).help(item.pinned ? T("Открепить") : T("Закрепить"))
            Button { history.remove(item.id) } label: {
                Image(systemName: "xmark").foregroundColor(.secondary)
            }
            .buttonStyle(.plain).help(T("Убрать из истории"))
        }
        .padding(.horizontal, 8).padding(.vertical, 6)
        .background(RoundedRectangle(cornerRadius: 7).fill(selected ? Color.accentColor.opacity(0.22) : Color.clear))
        .contentShape(Rectangle())
        .onTapGesture { onPick(item) }
        .onHover { if $0 { ui.selected = i } }
    }

    @ViewBuilder private func content(_ item: ClipItem) -> some View {
        switch item.kind {
        case .text:
            Text(item.singleLine).lineLimit(1).truncationMode(.tail)
        case .image:
            HStack(spacing: 6) {
                if let t = item.thumb {
                    Image(nsImage: t).resizable().scaledToFit().frame(maxWidth: 80, maxHeight: 34)
                }
                Text(T("Изображение") + (item.label.isEmpty ? "" : " " + item.label)).foregroundColor(.secondary)
            }
        case .files:
            HStack(spacing: 5) {
                Image(systemName: "doc").foregroundColor(.secondary)
                Text(item.urls[0].lastPathComponent + (item.urls.count > 1 ? " +\(item.urls.count - 1)" : ""))
                    .lineLimit(1).truncationMode(.middle)
            }
        }
    }
}

// MARK: Панель у курсора (⇧⌘V)

final class ClipPanel: NSPanel {
    var onKey: ((NSEvent) -> Bool)?
    var onResign: (() -> Void)?
    override var canBecomeKey: Bool { true }
    override var canBecomeMain: Bool { false }
    override func keyDown(with event: NSEvent) {
        if onKey?(event) != true { super.keyDown(with: event) }
    }
    override func resignKey() {
        super.resignKey()
        onResign?()
    }
}

final class ClipPanelController {
    static let shared = ClipPanelController()
    private var panel: ClipPanel?
    private let ui = ClipUI()
    private var stickerTarget: UUID?                 // стикер, по которому щёлкнули перед вызовом списка: вставка пойдёт в него
    private let digitCodes: [UInt16] = [18, 19, 20, 21, 23, 22, 26, 28, 25, 29]

    func toggle() {
        if panel?.isVisible == true { close() } else { show() }
    }

    func close() {
        guard let p = panel else { return }
        p.onResign = nil
        p.orderOut(nil)
        panel = nil
    }

    private func show() {
        let h = ClipboardHistory.shared
        guard h.enabled else { return }
        ui.selected = 0
        let view = ClipListView(history: h, ui: ui, pasteMode: true) { [weak self] item in self?.pick(item) }
            .background(VisualEffect())
            .clipShape(RoundedRectangle(cornerRadius: 12, style: .continuous))
        let host = NSHostingView(rootView: view)
        let size = host.fittingSize
        host.frame = NSRect(origin: .zero, size: size)

        let p = ClipPanel(contentRect: NSRect(origin: .zero, size: size),
                          styleMask: [.borderless, .nonactivatingPanel], backing: .buffered, defer: false)
        p.isOpaque = false
        p.backgroundColor = .clear
        p.hasShadow = true
        // в режиме «Показать стикеры» (затемнение и стикеры выше всех окон) список должен быть над ними
        p.level = StickerManager.shared.spotlightOn ? NSWindow.Level(rawValue: StickerManager.spotlightLevel.rawValue + 1) : .popUpMenu
        p.collectionBehavior = [.canJoinAllSpaces, .fullScreenAuxiliary, .transient]
        p.hidesOnDeactivate = false
        p.contentView = host
        p.onKey = { [weak self] e in self?.handleKey(e) ?? false }
        p.onResign = { [weak self] in self?.close() }

        // у курсора, но целиком на экране
        let m = NSEvent.mouseLocation
        let screen = NSScreen.screens.first { $0.frame.contains(m) } ?? NSScreen.main
        var o = NSPoint(x: m.x + 8, y: m.y - size.height - 8)
        if let vf = screen?.visibleFrame {
            o.x = min(max(o.x, vf.minX + 6), vf.maxX - size.width - 6)
            o.y = min(max(o.y, vf.minY + 6), vf.maxY - size.height - 6)
        }
        p.setFrameOrigin(o)
        panel = p
        stickerTarget = StickerManager.shared.keyStickerID()
        p.makeKeyAndOrderFront(nil)
    }

    private func pick(_ item: ClipItem) {
        close()
        if let t = stickerTarget {                   // вставка в стикер идёт напрямую: нажатие ⌘V ушло бы в программу под ним (на рабочем столе — в Finder)
            stickerTarget = nil
            ClipboardHistory.shared.copy(item)
            StickerManager.shared.insertFromClipboard(t)
            return
        }
        ClipboardHistory.shared.paste(item)
    }

    private func handleKey(_ e: NSEvent) -> Bool {
        let h = ClipboardHistory.shared
        let list = h.ordered
        switch e.keyCode {
        case 53: close()
        case 126: ui.selected = max(0, ui.selected - 1)
        case 125: ui.selected = min(max(0, list.count - 1), ui.selected + 1)
        case 36, 76:
            if list.indices.contains(ui.selected) { pick(list[ui.selected]) }
        case 51, 117:
            if list.indices.contains(ui.selected) {
                h.remove(list[ui.selected].id)
                ui.selected = max(0, min(ui.selected, h.ordered.count - 1))
            }
        case 35:
            if list.indices.contains(ui.selected) {
                let id = list[ui.selected].id
                h.togglePin(id)
                if let i = h.ordered.firstIndex(where: { $0.id == id }) { ui.selected = i }
            }
        default:
            if let n = digitCodes.firstIndex(of: e.keyCode), list.indices.contains(n) { pick(list[n]) }
        }
        return true
    }
}
