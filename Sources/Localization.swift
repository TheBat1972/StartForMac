import Foundation
import AppKit
import SwiftUI

enum AppLanguage: String, CaseIterable {
    case system, ru, en
}

/// Перерисовывает содержимое окна инструмента при смене языка в настройках «Пуска»
struct LangRefresh<Content: View>: View {
    @State private var tick = 0
    let content: () -> Content
    init(@ViewBuilder _ content: @escaping () -> Content) { self.content = content }
    var body: some View {
        content()
            .id(tick)
            .onReceive(NotificationCenter.default.publisher(for: .languageChanged)) { _ in tick += 1 }
    }
}

enum AppTheme: String, CaseIterable {
    case system, light, dark

    private static let key = "appTheme"

    static var setting: AppTheme {
        get { AppTheme(rawValue: UserDefaults.standard.string(forKey: key) ?? "") ?? .system }
        set { UserDefaults.standard.set(newValue.rawValue, forKey: key) }
    }

    /// Применяет выбранную тему ко всем окнам программы
    static func apply() {
        switch setting {
        case .system: NSApp.appearance = nil
        case .light: NSApp.appearance = NSAppearance(named: .aqua)
        case .dark: NSApp.appearance = NSAppearance(named: .darkAqua)
        }
    }
}

enum Loc {
    private static let key = "appLanguage"

    static var setting: AppLanguage {
        get { AppLanguage(rawValue: UserDefaults.standard.string(forKey: key) ?? "") ?? .system }
        set {
            UserDefaults.standard.set(newValue.rawValue, forKey: key)
            english = resolveEnglish()
        }
    }

    private static func resolveEnglish() -> Bool {
        switch setting {
        case .ru: return false
        case .en: return true
        case .system: return !(Locale.preferredLanguages.first?.hasPrefix("ru") ?? false)
        }
    }

    static var english: Bool = resolveEnglish()
}

/// Перевод строки (для русского возвращает её же; незнакомые строки, например имена своих категорий, не меняются)
func T(_ s: String) -> String {
    guard Loc.english else { return s }
    return translations[s] ?? s
}

/// Перевод строки с подстановками (%@)
func Tf(_ s: String, _ args: String...) -> String {
    let fmt = T(s)
    var out = fmt
    for a in args {
        if let r = out.range(of: "%@") { out.replaceSubrange(r, with: a) }
    }
    return out
}

