// Локализация: русский (исходный) и английский. Язык: как в системе / русский / English.
// Русский текст в коде служит ключом; для английского ищем перевод в словаре.

import Foundation

enum AppLanguage: String, CaseIterable {
    case system, ru, en
}

enum Loc {
    private static let key = "appLanguage"

    static var setting: AppLanguage {
        get { AppLanguage(rawValue: UserDefaults.standard.string(forKey: key) ?? "") ?? .system }
        set {
            UserDefaults.standard.set(newValue.rawValue, forKey: key)
            english = resolveEnglish()
        }
    }

    private static func resolveEnglish() -> Bool {
        switch setting {
        case .ru: return false
        case .en: return true
        case .system: return !(Locale.preferredLanguages.first?.hasPrefix("ru") ?? false)
        }
    }

    static var english: Bool = resolveEnglish()
}

/// Перевод строки (для русского возвращает её же; незнакомые строки, например имена своих категорий, не меняются)
func T(_ s: String) -> String {
    guard Loc.english else { return s }
    return translations[s] ?? s
}

/// Перевод строки с подстановками (%@)
func Tf(_ s: String, _ args: String...) -> String {
    let fmt = T(s)
    var out = fmt
    for a in args {
        if let r = out.range(of: "%@") { out.replaceSubrange(r, with: a) }
    }
    return out
}

